/** The Connect protocol over the generated HTTP API (docs/09 §25): what the generator writes for it. */
import { describe, expect, test } from "bun:test";
import { protoFiles, validateModelText } from "@ddd/core";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { generateTypeScript } from "../src/index.ts";

const ROOT = join(import.meta.dir, "../../..");
const EXAMPLE = readFileSync(join(ROOT, "examples/cleaning-platform-ts/model.ddd.yaml"), "utf8");
const IDENTITIES = readFileSync(join(import.meta.dir, "fixtures/identities.ddd.yaml"), "utf8");

function generate(text: string) {
  const r = validateModelText(text);
  if (!r.ok) throw new Error(JSON.stringify(r.diagnostics.filter((d) => d.severity === "error"), null, 2));
  return { out: generateTypeScript(r.analysis!, text), analysis: r.analysis! };
}

const asConnect = (text: string) =>
  text.replace(/^generation:\n/m, "generation:\n  target: typescript\n  typescript:\n    api: { base_path: /rpc, connect: true }\n");

describe("Connect over the generated HTTP API", () => {
  const { out, analysis } = generate(EXAMPLE);
  const file = (p: string) => out.files.find((f) => f.path === p)?.content ?? "";
  const connect = file("src/cleaning_platform/generated/api/connect-schema.ts");
  const server = file("src/cleaning_platform/generated/api/connect.ts");
  const client = file("src/cleaning_platform/generated/api/connect-client.ts");

  test("every served use case and query is a procedure, with the endpoint that serves it", () => {
    expect(connect).toContain('"/cleaning_staff.v1.CleaningStaffService/IssueInvitation": {\n      method: "POST",\n      path: "/api/cleaning-staff/issue-invitation",');
    expect(connect).toContain('"/cleaning_staff.v1.CleaningStaffService/SearchInvitations": {\n      method: "GET",\n      path: "/api/cleaning-staff/queries/search-invitations",');
    // register_staff is internal (run by a policy): it has no endpoint, so no procedure either.
    expect(connect).not.toContain("RegisterStaff");
    expect(server).toContain("return connectHandler(createApiHandler(...args), connectSchema, { basePath: \"/api\" });");
    // The typed client over Connect: the REST client's methods with a Connect fetch.
    expect(client).toContain("return createApiClient({ ...rest, fetch: connectFetch(connectSchema, transport) });");
  });

  test("protobuf JSON shapes: enums by name, value objects as messages, the tenant of a cross-tenant use case", () => {
    expect(connect).toContain('const cleaningStaffInvitationStatus = enumOf("INVITATION_STATUS_", [');
    expect(connect).toContain('"cleaning_staff.v1.EmailAddress": [f(1, "value", T.string)],');
    // Field numbers as the .proto writer numbers them; the tenant of a cross-tenant use case is field 1.
    expect(connect).toContain('request: [f(1, "tenant_id", T.string), f(2, "invitation_id", T.string)],');
    expect(connect).toContain('request: [\n        f(1, "email", msg("cleaning_staff.v1.EmailAddress")),\n        f(2, "valid_until", T.timestamp),\n      ],');
    expect(connect).toContain("response: result(cleaningStaffInvitationStatus),");
  });

  test("the contract it serves is in generated/proto/, the same files as `ddd migrate --split` writes", () => {
    const proto = file("src/cleaning_platform/generated/proto/cleaning_staff/v1/cleaning_staff.proto");
    expect(proto).toStartWith('// Generated by DDD Presenter from model "cleaning-platform". DO NOT EDIT.');
    expect(proto).toEndWith(protoFiles(analysis.model, analysis)["cleaning_staff/v1/cleaning_staff.proto"]!);
    // The cross-tenant use case takes its tenant in the request, like the HTTP API's command.
    expect(proto).toContain("message InspectInvitationRequest {\n  // The tenant the use case acts in (cross_tenant; not a field of the model).\n  string tenant_id = 1 [(ddd.v1.type) = UUID];\n  string invitation_id = 2 [(ddd.v1.type) = UUID];\n}");
    expect(file("src/cleaning_platform/generated/proto/buf.yaml")).toStartWith("# Generated by DDD Presenter");
  });

  test("Integer identities and results travel as int64 strings; the base path is the API's", () => {
    const { out: ids } = generate(asConnect(IDENTITIES));
    const c = ids.files.find((f) => f.path.endsWith("generated/api/connect-schema.ts"))!.content;
    expect(c).toContain('request: [f(1, "number", T.int64), f(2, "label", T.string)],');
    expect(ids.files.find((f) => f.path.endsWith("generated/api/connect.ts"))!.content).toContain('{ basePath: "/rpc" }');
  });

  test("without connect: true nothing of it is generated", () => {
    const { out: plain } = generate(EXAMPLE.replace(", connect: true", ""));
    expect(plain.files.some((f) => /connect|\/proto\//.test(f.path))).toBe(false);
  });

  const BUF = process.env.BUF ?? "buf";
  test.skipIf(!!spawnSync(BUF, ["--version"]).error)("buf builds and lints generated/proto/", () => {
    const dir = mkdtempSync(join(tmpdir(), "ddd-connect-proto-"));
    for (const f of out.files.filter((x) => x.path.includes("/generated/proto/"))) {
      const p = join(dir, f.path.split("/generated/proto/")[1]!);
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, f.content);
    }
    for (const cmd of ["build", "lint"]) {
      const r = spawnSync(BUF, [cmd], { cwd: dir, encoding: "utf8" });
      expect({ cmd, out: r.stdout + r.stderr, status: r.status }).toEqual({ cmd, out: "", status: 0 });
    }
  });
});
