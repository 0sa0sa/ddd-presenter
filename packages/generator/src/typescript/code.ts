/**
 * Collects imports of one file. Modules are external package names (`zod`) or project-relative module paths without
 * extension (`src/pkg/generated/runtime`), rendered as relative `.js` specifiers (ESM / NodeNext). Names used only
 * as types are imported with `import type` (verbatimModuleSyntax).
 */
export class TsImports {
  private readonly values = new Map<string, Set<string>>();
  private readonly types = new Map<string, Set<string>>();
  private readonly namespaces = new Map<string, string>();

  /** `self`: module path of the file being written (imports from itself are dropped). */
  constructor(private readonly self: string) {}

  value(module: string, ...names: string[]): this {
    if (module === this.self) return this;
    const set = this.values.get(module) ?? new Set<string>();
    for (const n of names) set.add(n);
    this.values.set(module, set);
    return this;
  }

  type(module: string, ...names: string[]): this {
    if (module === this.self) return this;
    const set = this.types.get(module) ?? new Set<string>();
    for (const n of names) set.add(n);
    this.types.set(module, set);
    return this;
  }

  namespace(module: string, alias: string): this {
    this.namespaces.set(module, alias);
    return this;
  }

  render(): string {
    const modules = [...new Set([...this.values.keys(), ...this.types.keys(), ...this.namespaces.keys()])];
    const spec = (m: string) => (isExternal(m) ? m : relativeSpecifier(this.self, m));
    const external = modules.filter(isExternal).sort();
    const local = modules.filter((m) => !isExternal(m)).sort((a, b) => spec(a).localeCompare(spec(b)));
    const lines: string[] = [];
    for (const group of [external, local]) {
      for (const m of group) {
        const ns = this.namespaces.get(m);
        if (ns) lines.push(`import * as ${ns} from "${spec(m)}";`);
        const values = this.values.get(m) ?? new Set<string>();
        const types = [...(this.types.get(m) ?? [])].filter((t) => !values.has(t));
        if (!values.size && !types.length) continue;
        const names = [...[...values].map((v) => ({ n: v, t: false })), ...types.map((t) => ({ n: t, t: true }))].sort((a, b) => a.n.localeCompare(b.n));
        if (!values.size) lines.push(`import type { ${names.map((x) => x.n).join(", ")} } from "${spec(m)}";`);
        else lines.push(`import { ${names.map((x) => (x.t ? `type ${x.n}` : x.n)).join(", ")} } from "${spec(m)}";`);
      }
      if (group === external && external.length && local.length) lines.push("");
    }
    return lines.join("\n");
  }
}

/** Packages the generated code imports; every other module is a project-relative path. */
const EXTERNAL = new Set(["zod", "decimal.js", "vitest", "bun:test", "node:crypto", "@tanstack/react-query", "react", "jose"]);

function isExternal(m: string): boolean {
  return EXTERNAL.has(m);
}

/** `./x.js` / `../a/b.js` from the module `from` to the module `to` (both project-relative, no extension). */
export function relativeSpecifier(from: string, to: string): string {
  const a = from.split("/").slice(0, -1);
  const b = to.split("/");
  let i = 0;
  while (i < a.length && i < b.length - 1 && a[i] === b[i]) i++;
  const up = a.length - i;
  const rest = b.slice(i).join("/");
  return `${up === 0 ? "./" : "../".repeat(up)}${rest}.js`;
}

/** File header, imports and body; over-long lines are re-printed with Prettier's rules (format.ts). */
export function assemble(head: string, doc: string | undefined, imports: TsImports, body: string): string {
  const parts = [head];
  if (doc) parts.push(docLines(doc, "").join("\n"));
  const imp = imports.render();
  if (imp) parts.push(imp);
  return formatSource(parts.join("\n\n") + "\n\n" + body.trim() + "\n");
}
